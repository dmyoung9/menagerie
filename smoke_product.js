// Run with: playwright-cli -s=menagerie-polish run-code --filename=smoke_product.js
// Uses an isolated frontend at :8037 and intercepts every API call. No live state changes.
async (page) => {
  await page.unroute('**/api/**');
  const assert = (condition, text) => {if (!condition) throw new Error(text);};
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  page.on('console', e => {if(e.type()==='error'&&!e.text().startsWith('Failed to load resource:')) errors.push(e.text());});
  const writes = [];
  const profile = {id:'profile-a',name:'Example settings',revision:1,artifact_id:'model-a',runtime_id:'engine-a',config:{'ctx-size':32768,parallel:1},raw_args:[],catalog:{catalog_id:'example',model:{limit:{context:32768,output:1024}}}};
  const makeDeployment = (id, name, state, residency, enabled=true) => ({id,name,state,residency,enabled,profile_id:profile.id,profile_snapshot:profile,revision:1,alias:id,port:8120,priority:50,idle_timeout:300,gpu:0,queue_timeout:300,reservation_mib:0,allow_eviction:false,allow_uncertain:false,lifecycle:{serving:enabled && (state==='READY'||residency==='on-demand'),failure:state==='FAILED'?'Runtime exited unexpectedly':null,last_stop_reason:state==='STOPPED'?'Idle unload':null}});
  let registry = {
    models:[{id:'model-a',name:'Example 27B',format:'gguf',size_bytes:8*1024**3,architecture:'example',local_path:'/models/example.gguf',source:'local'}],
    runtimes:[{id:'engine-a',name:'llama.cpp',engine:'llama.cpp',execution_kind:'native',executable:'/engines/llama-server',env:{},command_template:[],trust:true,capabilities:{formats:['gguf'],schema:{'ctx-size':{type:'integer',min:512,max:1048576},parallel:{type:'integer',min:1,max:64},'gpu-layers':{type:'string',default:'all'}}}}],
    profiles:[profile],deployments:[makeDeployment('ready','Example 27B','READY','on-demand'),makeDeployment('idle','Example 9B','STOPPED','on-demand'),makeDeployment('pinned','Example pinned','STOPPED','pinned'),makeDeployment('failed','Example failed','FAILED','on-demand'),makeDeployment('inactive','Example inactive','STOPPED','on-demand',false)],groups:[],jobs:[],
  };
  const settings = {sample_seconds:2,retention_days:7,summary_days:90,history_quota_mib:512,gpu_headroom_mib:2048,ram_headroom_mib:4096,temperature_limit:85,max_queue:32,expose_on_demand:true};
  const host={ts:1700000000,gpus:[{index:0,name:'Test GPU',used_mib:6350,total_mib:16384,free_mib:10034,temperature:35,utilization:0}],ram_total_mib:32768,ram_available_mib:24000,deployments:{ready:{gpu_mib:6200}},processes:[]};
  let failDeployment = false, uncertain = true, failNetwork = false;
  await page.route('**/api/**', async route => {
    const req=route.request(), path=req.url().replace(/^https?:\/\/[^/]+/, '').split('?')[0];
    if(failNetwork) return route.abort();
    const payload=req.method()==='POST'?req.postDataJSON():null;
    if(payload) writes.push({path,payload});
    const send=(body,status=200)=>route.fulfill({status,contentType:'application/json',body:JSON.stringify(body)});
    if(path==='/api/status') return send({csrf_token:'test-token',host,settings,gateway_url:'http://127.0.0.1:9123/v1',deployments:registry.deployments.map(d=>({...d,inflight:d.id==='ready'?1:0}))});
    if(path.startsWith('/api/registry/')) return send(registry[path.split('/').at(-1)]||[]);
    if(path==='/api/integration/opencode') return send({endpoint:'http://127.0.0.1:9123/v1'});
    if(path==='/api/events/stream') return route.fulfill({contentType:'text/event-stream',body:'id: 1\nevent: operation\ndata: '+JSON.stringify({seq:1,ts:1700000000,kind:'state',deployment_id:'idle',data:{to:'STOPPED',reason:'Idle unload'}})+'\n\n'});
    if(path==='/api/history/metrics') return send([{...host,ts:1699999900},host]);
    if(path.endsWith('/logs')) return send({text:'Runtime ready\nNo requests in flight'});
    if(path==='/api/deployments'&&payload) {if(failDeployment){failDeployment=false;return send({error:'Alias already exists'},409);}const row={...makeDeployment(payload.id||'new-deployment',payload.name,'STOPPED',payload.residency),...payload,profile_snapshot:payload.configuration};registry.deployments=[...registry.deployments.filter(d=>d.id!==row.id),row];return send(row);}
    if(path.endsWith('/validate')) return send({errors:[],warnings:uncertain?['Low-confidence memory estimate.']:[],estimates:{idle:{reservation_mib:6800,confidence:'low'}},stops:[],plan_token:'review-token'});
    if(path.endsWith('/start')) return send({state:'QUEUED'});
    if(path.startsWith('/api/history/')) return send([]);
    if(path==='/api/models/local') return send({state:'QUEUED'});
    return send({error:'Unmocked route: '+path},500);
  });
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:8037/');
  await page.getByRole('heading',{name:'Overview',exact:true}).waitFor();
  await page.getByText('Example 9B unloaded · Idle unload',{exact:true}).waitFor();
  assert(await page.getByRole('cell',{name:'—',exact:true}).count()>0,'Missing table telemetry should remain unknown');
  await page.getByRole('button',{name:'Connect client'}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByText('http://127.0.0.1:9123/v1',{exact:true}).waitFor();
  assert(!(await dialog.locator('pre').innerText()).split('\n').some(line=>line.startsWith('+')),'Example request contains diff debris');
  await dialog.getByRole('button',{name:'OpenCode',exact:true}).click();
  await dialog.getByText('menagerie plugin install --gateway-port 9123',{exact:true}).waitFor();
  await page.keyboard.press('Escape');
  assert(await page.getByRole('button',{name:'Connect client'}).evaluate(el=>el===document.activeElement),'Dialog did not restore focus');
  await page.getByRole('navigation').getByRole('link',{name:'Deployments'}).click();
  const readyRow=page.getByRole('row').filter({has:page.getByRole('link',{name:'Example 27B',exact:true})});
  assert(await readyRow.getByRole('button',{name:'Unload',exact:true}).isEnabled(),'Coordinated unload should be available while waiting for requests');
  const idleRow=page.getByRole('row').filter({has:page.getByRole('link',{name:'Example 9B',exact:true})});
  await idleRow.locator('summary').click();
  await idleRow.getByRole('button',{name:'Details',exact:true}).click();
  await page.getByRole('heading',{name:'Example 9B',exact:true}).waitFor();
  await page.getByRole('button',{name:'Configuration',exact:true}).click();
  assert(page.url().endsWith('/configuration'),'Details must be linkable');
  await page.goBack();
  await page.getByRole('button',{name:'Overview',exact:true}).waitFor();
  await page.getByRole('button',{name:'Logs',exact:true}).click();
  await page.getByText('Runtime ready',{exact:false}).waitFor();
  await page.getByRole('navigation').getByRole('link',{name:'Deployments'}).click();
  await page.getByRole('button',{name:'Inactive (1)',exact:true}).click();
  await page.getByRole('link',{name:'Example inactive',exact:true}).waitFor();
  await page.getByRole('button',{name:'Enabled (4)',exact:true}).click();
  await page.getByRole('button',{name:'New deployment',exact:true}).click();
  await dialog.getByLabel('Name',{exact:true}).fill('Composed deployment');
  await dialog.getByRole('button',{name:'Add model',exact:true}).click();
  await dialog.getByLabel('API model ID',{exact:true}).fill('composed-model');
  await dialog.getByLabel('ctx-size',{exact:true}).fill('65536');
  await dialog.getByLabel('parallel',{exact:true}).fill('2');
  failDeployment=true;
  await dialog.getByRole('button',{name:'Save deployment',exact:true}).click();
  await dialog.getByRole('alert').filter({hasText:'Alias already exists'}).waitFor();
  await dialog.getByRole('button',{name:'Save deployment',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  await page.getByRole('button',{name:'Load now',exact:true}).click();
  await dialog.getByRole('heading',{name:'Review launch',exact:true}).waitFor();
  const saved = writes.find(w=>w.path==='/api/deployments').payload.configuration;
  assert(saved.config['ctx-size']===65536&&saved.config.parallel===2,'Per-request context must map to shared engine pool');
  assert(saved.config['gpu-layers']==='all','Supported GPU defaults were not applied');
  assert(!writes.some(w=>w.path==='/api/profiles'),'Deployment creation must not require a separate profile write');
  assert(await dialog.getByRole('button',{name:'Load',exact:true}).isDisabled(),'Uncertain launch needs approval');
  await dialog.getByRole('checkbox').check();
  await dialog.getByRole('button',{name:'Load',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert(writes.some(w=>w.path.endsWith('/start')&&w.payload.override&&w.payload.plan_token==='review-token'),'Launch approval was not submitted');
  uncertain=false;
  await page.getByRole('button',{name:'Load now',exact:true}).click();
  await dialog.getByRole('heading',{name:'Review launch',exact:true}).waitFor();
  assert(await dialog.getByRole('checkbox').count()===0,'Certain launch should not require boilerplate acceptance');
  await page.keyboard.press('Escape');
  await page.getByRole('navigation').getByRole('link',{name:'Settings'}).click();
  await page.getByRole('heading',{name:'Settings',exact:true}).waitFor();
  assert(await page.getByRole('button',{name:'Migration',exact:true}).count()===0,'Settings should not expose a personal migration workflow');
  await page.getByRole('button',{name:'Register engine',exact:true}).click();
  await dialog.getByLabel('Executable path',{exact:true}).fill('/runtime/server');
  await dialog.getByRole('checkbox').check();
  await dialog.getByRole('button',{name:'Save',exact:true}).click();
  await dialog.getByRole('alert').waitFor();
  assert(await dialog.getByLabel('Executable path',{exact:true}).inputValue()==='/runtime/server','Failed save lost form input');
  page.once('dialog', d => d.accept());
  await page.keyboard.press('Escape');
  assert(await page.getByRole('button',{name:'Profiles',exact:true}).count()===0,'Profiles should not be a product concept');
  await page.getByRole('navigation').getByRole('link',{name:'Deployments'}).click();
  await page.getByRole('link',{name:'Example 9B',exact:true}).click();
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  assert(await dialog.getByLabel('Profile revision').count()===0,'Editing must not require selecting a profile');
  await dialog.getByLabel('Display name',{exact:true}).fill('Renamed directly');
  await dialog.getByLabel('ctx-size',{exact:true}).fill('16384');
  await dialog.locator('summary').filter({hasText:'Advanced model settings'}).click();
  await dialog.locator('summary').filter({hasText:'Runtime options (JSON)'}).click();
  await dialog.getByLabel('Runtime options (JSON)',{exact:true}).fill('{invalid');
  assert(await dialog.getByRole('button',{name:'Save',exact:true}).isDisabled(),'Invalid JSON must prevent saving');
  await dialog.getByLabel('Runtime options (JSON)',{exact:true}).fill('{"ctx-size":16384,"parallel":1}');
  await dialog.getByRole('button',{name:'Save',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  const edited=writes.filter(w=>w.path==='/api/deployments').at(-1).payload;
  assert(edited.name==='Renamed directly'&&edited.configuration.config['ctx-size']===16384,'Deployment editing lost direct settings');
  assert(!edited.profile_id,'Editing should use deployment-owned configuration');
  for(const section of ['Overview','Models','Deployments','Activity','Settings']) {
    await page.getByRole('navigation').getByRole('link',{name:section,exact:true}).click();
    await page.getByRole('heading',{name:section,exact:true}).waitFor();
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),section+' overflows mobile viewport');
    await page.setViewportSize({width:1440,height:1000});
  }
  await page.getByRole('navigation').getByRole('link',{name:'Overview',exact:true}).click();
  await page.getByRole('heading',{name:'Overview',exact:true}).waitFor();
  await page.screenshot({path:'/tmp/opencode/menagerie-polish-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/tmp/opencode/menagerie-polish-mobile.png',fullPage:true});
  registry={models:[],runtimes:[],profiles:[],deployments:[],groups:[],jobs:[]};
  await page.reload();
  await page.getByRole('heading',{name:'Add your first model'}).waitFor();
  await page.getByRole('navigation').getByRole('link',{name:'Models',exact:true}).click();
  await page.getByRole('heading',{name:'No models yet'}).waitFor();
  await page.getByRole('button',{name:'Add from File',exact:true}).last().click();
  await dialog.getByRole('textbox').fill('/models/example.gguf');
  await dialog.getByRole('button',{name:'Add from File',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert(writes.some(w=>w.path==='/api/models/local'&&w.payload.path==='/models/example.gguf'),'Add from File did not submit the host-local path');
  failNetwork=true;
  await page.reload();
  await page.getByRole('alert').filter({hasText:'Connection lost'}).waitFor();
  assert(!errors.length,errors.join('\n'));
  await page.evaluate(() => {window.productSmokePassed = true;});
  return {result:'passed',checks:['navigation and browser Back','dialog focus','unload action','inactive filter','logs','shared context controls','atomic creation retry','direct configuration editing','no profile workflow','uncertainty consent','failed-save preservation','invalid JSON guard','five mobile views','clean installation','disconnection'],writesIntercepted:writes.length};
}
