// Isolated Vite frontend at :8037; all API calls are mocked, no live state changes.
async page => {
  await page.context().route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:8037' ? route.continue() : route.abort());
  await page.unroute('**/api/**');
  const assert = (condition, text) => {if (!condition) throw new Error(text);};
  const errors = [], writes = [];
  page.on('pageerror', e => errors.push(String(e)));
  const hints = {input:['text','image'],output:['text'],tools:true,reasoning:true,thinking_toggle:true,reasoning_effort:['none','low','medium','high'],evidence:['chat template controls'],dependencies:[],note:'Detected hints, not proof of engine support.'};
  const models = ['Q4_K_M','Q8_0'].map((quant,i)=>({id:'m'+i,name:'Example-8B-'+quant,repo:'example/Example-8B-GGUF',source:'huggingface',format:'gguf',size_bytes:5*1024**3,local_path:'/models/'+quant+'.gguf',quantization:quant,discovered_capabilities:hints}));
  const engine = {id:'e',name:'llama.cpp',engine:'llama.cpp',capabilities:{formats:['gguf'],schema:{'ctx-size':{type:'integer',min:512,max:1048576},parallel:{type:'integer',min:1,max:64}}}};
  let deployments=[];
  await page.route('**/api/**', async route => {
    const req = route.request(), path = req.url().replace(/^https?:\/\/[^/]+/, '').split('?')[0];
    const body = req.method()==='POST' ? req.postDataJSON() : null;
    if(body) writes.push({path,body});
    const send = value => route.fulfill({contentType:'application/json',body:JSON.stringify(value)});
    if(path==='/api/status') return send({csrf_token:'test',host:{},settings:{},gateway_url:'http://127.0.0.1:8001/v1'});
    if(path.startsWith('/api/registry/')) return send(({models,runtimes:[engine],profiles:[],deployments,jobs:[]})[path.split('/').at(-1)]||[]);
    if(path==='/api/integration/opencode') return send({endpoint:'http://127.0.0.1:8001/v1'});
    if(path==='/api/events/stream') return route.fulfill({contentType:'text/event-stream',body:''});
    if(path==='/api/resources/preview') return send({members:[],gpus:[],warnings:[]});
    if(path==='/api/deployments') {const row={...body,id:'saved',revision:1,state:'STOPPED',profile_snapshot:body.configuration}; deployments=[row]; return send(row);}
    return send([]);
  });
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:8037/#/models/installed');
  await page.reload();
  await page.getByText('2 installed variants',{exact:true}).waitFor();
  assert(await page.locator('.catalog-grid > [data-slot="card"]').count()===1,'Known repository variants should share a card');
  await page.getByLabel('Filter model capability').selectOption('audio');
  await page.getByText('No matching models',{exact:true}).waitFor();
  await page.getByLabel('Filter model capability').selectOption('reasoning');
  await page.getByRole('button',{name:'Choose variant',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Installed variant').selectOption('m1');
  await dialog.getByRole('button',{name:'Create deployment',exact:true}).click();
  await dialog.getByRole('button',{name:'Add model',exact:true}).click();
  await dialog.getByRole('heading',{name:'Capabilities',exact:true}).waitFor();
  const reasoning = dialog.getByRole('group',{name:'Reasoning options',exact:true});
  await reasoning.getByRole('button',{name:'Instant',exact:true}).click();
  await reasoning.getByRole('button',{name:'High',exact:true}).click();
  assert(await reasoning.getByRole('button',{name:'Low',exact:true}).getAttribute('aria-pressed')==='false','Unselected reasoning option must remain hidden');
  await dialog.getByRole('group',{name:'Input capabilities',exact:true}).getByRole('button',{name:'Images',exact:true}).click();
  assert(await dialog.locator('.capabilities-panel textarea:visible').count()===0,'Normal capabilities must not show JSON editors');
  assert(await dialog.locator('.capabilities-panel').evaluate(el=>el.getBoundingClientRect().height)<480,'Capabilities should be compact');
  await page.setViewportSize({width:390,height:844});
  await dialog.locator('.capabilities-panel').scrollIntoViewIfNeeded();
  assert(await dialog.locator('.capabilities-panel').evaluate(el=>el.getBoundingClientRect().height)<480,'Mobile capability section needs too much scrolling');
  assert(await dialog.locator('.capabilities-panel [data-slot="toggle-group-item"]').first().evaluate(el=>el.getBoundingClientRect().height)>=44,'Mobile chips need touch-sized targets');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile editor horizontal overflow');
  await dialog.getByRole('button',{name:'Save deployment',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  await page.waitForURL('**/deployments/saved');
  const saved = writes.find(w=>w.path==='/api/deployments').body.configuration;
  assert(saved.artifact_id==='m1','Wrong installed variant selected');
  assert(saved.catalog.model.capabilities.input.includes('image'),'Image input declaration lost');
  const exposed=saved.catalog.reasoning.presets.filter(p=>p.enabled);
  assert(exposed.map(p=>p.id).join(',')==='default,instant,high','Wrong reasoning exposure');
  assert(exposed.find(p=>p.id==='instant').body.reasoning_effort==='none','Instant mapping lost');
  await page.goto('http://127.0.0.1:8037/#/models/installed');
  await page.setViewportSize({width:390,height:844});
  await page.getByText('2 installed variants',{exact:true}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile horizontal overflow');
  await page.getByRole('button',{name:'Details',exact:true}).click();
  await dialog.getByLabel('Installed variant').waitFor();
  await page.keyboard.press('Escape');
  await dialog.waitFor({state:'hidden'});
  const logo = page.locator('.brand img');
  assert(await logo.evaluate(img=>img.complete&&img.naturalWidth>0),'Bundled logo did not load');
  // Unknown effort levels need setup; configuring one must not reset Instant.
  hints.reasoning_effort=[];
  await page.reload();
  await page.getByRole('button',{name:'Choose variant',exact:true}).click();
  await dialog.getByRole('button',{name:'Create deployment',exact:true}).click();
  await dialog.getByRole('button',{name:'Add model',exact:true}).click();
  await reasoning.getByRole('button',{name:'Instant',exact:true}).click();
  assert(await reasoning.getByRole('button',{name:'High',exact:true}).isDisabled(),'Unknown High control must not be guessed');
  await dialog.getByRole('button',{name:'Set up',exact:true}).click();
  await dialog.getByLabel('High control',{exact:true}).selectOption('effort');
  await dialog.getByLabel('Medium control',{exact:true}).selectOption('custom');
  await dialog.getByLabel('Medium custom settings',{exact:true}).fill('{invalid');
  assert(await dialog.getByRole('button',{name:'Save deployment',exact:true}).isDisabled(),'Invalid advanced settings must prevent saving');
  await dialog.getByLabel('Medium custom settings',{exact:true}).fill('{"reasoning_budget":2048}');
  await dialog.locator('.capability-advanced > summary').click();
  await reasoning.getByRole('button',{name:'High',exact:true}).click();
  await dialog.getByRole('button',{name:'Save deployment',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  const second = writes.filter(w=>w.path==='/api/deployments').at(-1).body.configuration.catalog.reasoning.presets;
  assert(second.find(p=>p.id==='instant').body.chat_template_kwargs.enable_thinking===false,'Setting High reset detected Instant mapping');
  assert(second.find(p=>p.id==='high').enabled,'Configured High was not exposed');
  assert(second.find(p=>p.id==='medium').body.reasoning_budget===2048&&!second.find(p=>p.id==='medium').enabled,'Custom budget or exposure was lost');
  await page.waitForURL('**/deployments/saved');
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  await dialog.getByRole('group',{name:'Input capabilities',exact:true}).getByRole('button',{name:'Tools',exact:true}).click();
  await dialog.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.getByRole('alertdialog').getByRole('heading',{name:'Discard unsaved changes?'}).waitFor();
  await page.getByRole('alertdialog').getByRole('button',{name:'Keep editing'}).click();
  assert(await dialog.isVisible(),'Dismissing discard confirmation must keep the editor open');
  await dialog.getByRole('button',{name:'More deployment actions'}).click();
  await page.getByRole('menuitem',{name:'Remove',exact:true}).waitFor();
  await page.keyboard.press('Escape');
  await dialog.getByRole('button',{name:'Save',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  assert(!errors.length,errors.join('\n'));
  await page.evaluate(()=>{window.capabilitySmokePassed=true;});
  return {checks:'grouping, filtering, variant selection, reasoning exposure, image declaration, mobile layout, Escape',writes:writes.length,errors};
}
